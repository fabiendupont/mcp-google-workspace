    fn policy_file_from_json(name: &str, json: &str) -> (std::path::PathBuf, Policy) {
        let dir =
            std::env::temp_dir().join(format!("mcp-gws-policy-{name}-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("policy.json");
        std::fs::write(&path, json).unwrap();
        let policy = Policy::from_file(&path).unwrap();
        (dir, policy)
    }

