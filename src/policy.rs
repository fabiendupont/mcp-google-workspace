use std::collections::{HashMap, HashSet};
use std::path::Path;

use serde::Deserialize;

use google_workspace::discovery::RestMethod;
use google_workspace::error::GwsError;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Access {
    ReadOnly,
    ReadWrite,
}

fn default_read_write() -> Access {
    Access::ReadWrite
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "kebab-case")]
#[derive(Default)]
pub enum ConstraintMode {
    #[default]
    Restrict,
    Protect,
}

#[derive(Debug, Clone, Deserialize)]
pub struct Constraint {
    pub param: String,
    pub values: Vec<String>,
    #[serde(default = "default_read_write")]
    pub access: Access,
    pub location: Option<String>,
    #[serde(default)]
    pub mode: ConstraintMode,
    #[serde(default)]
    pub recursive: bool,
}

#[derive(Debug, Clone, Deserialize)]
pub struct TemplateEntry {
    pub id: String,
    pub name: String,
    #[serde(default)]
    pub description: Option<String>,
}

#[derive(Debug, Deserialize, Default)]
pub struct PolicyFile {
    #[serde(default)]
    pub server: ServerPolicy,
    #[serde(default)]
    pub services: Vec<ServicePolicy>,
    #[serde(default)]
    pub templates: Vec<TemplateEntry>,
}

#[derive(Debug, Deserialize)]
pub struct ServerPolicy {
    #[serde(default)]
    pub read_only: bool,
    /// Require explicit user approval (MCP elicitation) before any write operation
    #[serde(default)]
    pub confirm_writes: bool,
    #[serde(default = "default_max_request_bytes")]
    pub max_request_bytes: usize,
    #[serde(default)]
    pub rate_limit_rpm: Option<u32>,
    #[serde(default)]
    pub rate_limits: Option<HashMap<String, u32>>,
    #[serde(default)]
    pub allowed_origins: Vec<String>,
    /// Polling interval (seconds) for subscriptions without webhook support
    #[serde(default = "default_subscription_poll_secs")]
    pub subscription_poll_secs: u64,
    #[serde(default)]
    pub credentials_file: Option<String>,
    #[serde(default)]
    pub project_id: Option<String>,
    #[serde(default)]
    pub delegate_subject: Option<String>,
    /// Subjects a client may request via `_meta.user_email` for domain-wide
    /// delegation. Empty by default: client-supplied subjects are rejected
    /// unless the operator opts in here.
    #[serde(default)]
    pub allowed_subjects: Vec<String>,
    /// Bearer token required to access this server instance (HTTP multi-user mode)
    #[serde(default)]
    pub api_token: Option<String>,
    /// CIDRs of reverse proxies in front of this listener. `X-Forwarded-For`
    /// is honoured for rate-limit keying only when the immediate peer is in
    /// this list; otherwise the peer address is used and the header is
    /// ignored. Empty (the default) means the header is never trusted, which
    /// is correct for a directly exposed listener.
    #[serde(default)]
    pub trusted_proxies: Vec<String>,
}

impl Default for ServerPolicy {
    fn default() -> Self {
        Self {
            read_only: false,
            confirm_writes: false,
            max_request_bytes: default_max_request_bytes(),
            rate_limit_rpm: None,
            rate_limits: None,
            allowed_origins: Vec::new(),
            subscription_poll_secs: default_subscription_poll_secs(),
            credentials_file: None,
            project_id: None,
            delegate_subject: None,
            allowed_subjects: Vec::new(),
            api_token: None,
            trusted_proxies: Vec::new(),
        }
    }
}

fn default_max_request_bytes() -> usize {
    16 * 1024 * 1024
}

fn default_subscription_poll_secs() -> u64 {
    60
}

/// Service aliases this server knows about, used to validate
/// `server.rate_limits` keys. A key must be one of these or a service listed in
/// the policy's own `services` array; anything else is a typo (for example the
/// documented-but-nonexistent `server.rate_limits.requests_per_minute`) and
/// would otherwise be accepted as an override for a service of that literal
/// name, silently doing nothing.
const KNOWN_SERVICES: &[&str] = &[
    "admin", "calendar", "chat", "docs", "drive", "gmail", "people", "sheets", "slides", "tasks",
];

/// Dangerous-method defaults applied when a service is enabled via the
/// `--services` shorthand. Mirrors the hardened entries generated by `init`.
pub fn baseline_denials(service: &str) -> Vec<String> {
    match service {
        "gmail" => [
            "messages.delete",
            "messages.trash",
            "messages.batchDelete",
            "settings.updateAutoForwarding",
            "settings.delegates.create",
            "settings.forwardingAddresses.create",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect(),
        // `files.delete` and `files.emptyTrash` are permanent destruction.
        "drive" => ["files.delete", "files.emptyTrash"]
            .iter()
            .map(|s| s.to_string())
            .collect(),
        _ => Vec::new(),
    }
}

#[derive(Debug, Clone, Deserialize, Default)]
pub struct ServicePolicy {
    pub name: String,
    #[serde(default)]
    pub read_only: Option<bool>,
    #[serde(default)]
    pub denied_methods: Vec<String>,
    #[serde(default)]
    pub constraints: Vec<Constraint>,
    #[serde(default)]
    pub allowed_labels: Vec<String>,
    #[serde(default)]
    pub allowed_resources: Vec<String>,
}

#[derive(Debug, Clone)]
pub struct Policy {
    pub global_read_only: bool,
    pub confirm_writes: bool,
    pub max_request_bytes: usize,
    pub rate_limit_rpm: Option<u32>,
    pub rate_limits: Option<HashMap<String, u32>>,
    pub allowed_origins: Vec<String>,
    pub subscription_poll_secs: u64,
    pub credentials_file: Option<String>,
    pub project_id: Option<String>,
    pub delegate_subject: Option<String>,
    /// Allowlist for client-requested delegation subjects (`_meta.user_email`).
    pub allowed_subjects: Vec<String>,
    pub api_token: Option<String>,
    /// Trusted reverse-proxy CIDRs for `X-Forwarded-For` derivation.
    pub trusted_proxies: Vec<String>,
    pub compact_schemas: bool,
    services: HashMap<String, ServicePolicy>,
    templates: Vec<TemplateEntry>,
}

impl Policy {
    pub fn from_file(path: &Path) -> Result<Self, GwsError> {
        let content = std::fs::read_to_string(path)
            .map_err(|e| GwsError::Validation(format!("Failed to read policy file: {e}")))?;
        let file: PolicyFile = serde_json::from_str(&content)
            .map_err(|e| GwsError::Validation(format!("Invalid policy JSON: {e}")))?;
        let policy = Self::from_policy_file(file);
        // Load-time gate for `[server]` knobs that would otherwise silently
        // disable a protection. `http::effective_body_limit` applies the same
        // fail-closed posture to `max_request_bytes` at transport startup.
        policy.validate_server_knobs()?;
        Ok(policy)
    }

    pub fn from_services(names: &[String]) -> Self {
        let file = PolicyFile {
            server: ServerPolicy::default(),
            services: names
                .iter()
                .map(|n| ServicePolicy {
                    name: n.clone(),
                    denied_methods: baseline_denials(n),
                    ..Default::default()
                })
                .collect(),
            templates: Vec::new(),
        };
        Self::from_policy_file(file)
    }

    /// Build a policy from an already-parsed [`PolicyFile`].
    ///
    /// File policies are literal: they inherit no baseline denials.
    /// [`baseline_denials`] is applied only by [`Self::from_services`], the
    /// `--services` shorthand. A policy file that lists `drive` without
    /// `denied_methods` therefore allows `files.delete`; operators must spell
    /// out every denial they want (the hardened templates generated by `init`
    /// carry the baseline themselves).
    ///
    /// This constructor cannot fail, so it does not run
    /// [`Self::validate_server_knobs`]; the file-based entry point
    /// [`Self::from_file`] validates before returning.
    pub fn from_policy_file(file: PolicyFile) -> Self {
        let mut services: HashMap<String, ServicePolicy> = file
            .services
            .into_iter()
            .map(|s| (s.name.clone(), s))
            .collect();

        if !file.templates.is_empty() {
            let template_ids: Vec<String> = file.templates.iter().map(|t| t.id.clone()).collect();
            let protect_params = [
                ("drive", "fileId"),
                ("slides", "presentationId"),
                ("docs", "documentId"),
            ];
            for (svc, param) in &protect_params {
                if let Some(svc_policy) = services.get_mut(*svc) {
                    let already_protected: Vec<&str> = svc_policy
                        .constraints
                        .iter()
                        .filter(|c| c.param == *param && c.mode == ConstraintMode::Protect)
                        .flat_map(|c| c.values.iter().map(|v| v.as_str()))
                        .collect();
                    let missing: Vec<String> = template_ids
                        .iter()
                        .filter(|id| !already_protected.contains(&id.as_str()))
                        .cloned()
                        .collect();
                    if !missing.is_empty() {
                        svc_policy.constraints.push(Constraint {
                            param: param.to_string(),
                            values: missing,
                            access: Access::ReadOnly,
                            location: None,
                            mode: ConstraintMode::Protect,
                            recursive: false,
                        });
                    }
                }
            }
        }

        Self {
            global_read_only: file.server.read_only,
            confirm_writes: file.server.confirm_writes,
            max_request_bytes: file.server.max_request_bytes,
            rate_limit_rpm: file.server.rate_limit_rpm,
            rate_limits: file.server.rate_limits,
            allowed_origins: file.server.allowed_origins,
            subscription_poll_secs: file.server.subscription_poll_secs,
            credentials_file: file.server.credentials_file,
            project_id: file.server.project_id,
            delegate_subject: file.server.delegate_subject,
            allowed_subjects: file.server.allowed_subjects,
            api_token: file.server.api_token,
            trusted_proxies: file.server.trusted_proxies,
            compact_schemas: false,
            services,
            templates: file.templates,
        }
    }

    /// Validate one `server.trusted_proxies` entry: `addr` or `addr/prefix`.
    fn validate_cidr(entry: &str) -> Result<(), String> {
        let entry = entry.trim();
        if entry.is_empty() {
            return Err("empty entry".to_string());
        }
        let (addr, prefix) = match entry.split_once('/') {
            Some((a, p)) => (a, Some(p)),
            None => (entry, None),
        };
        let ip: std::net::IpAddr = addr
            .parse()
            .map_err(|_| "the address part is not a valid IPv4/IPv6 address".to_string())?;
        if let Some(prefix) = prefix {
            let bits: u8 = prefix
                .parse()
                .map_err(|_| "the prefix length is not a number".to_string())?;
            let max = if ip.is_ipv4() { 32 } else { 128 };
            if bits > max {
                return Err(format!(
                    "the prefix length /{bits} exceeds /{max} for this address family"
                ));
            }
        }
        Ok(())
    }

    /// Reject `[server]` knobs whose disabled value would silently remove a
    /// protection.
    ///
    /// Two knobs fail closed here rather than being interpreted as "off":
    ///
    /// * `rate_limit_rpm: 0` — `rate_limit.rs` treats a zero budget as
    ///   "unlimited" in both the outbound per-service limiter and the inbound
    ///   per-client-IP limiter, which is the opposite of the adjacent
    ///   `max_request_bytes: 0` posture (that one refuses to start).
    /// * `rate_limits: { ... }` entries — this map is a per-service *outbound*
    ///   override keyed by service alias, not the HTTP request budget. Unknown
    ///   keys (notably the documented-but-nonexistent
    ///   `rate_limits.requests_per_minute`) and zero values are rejected so a
    ///   typo cannot silently no-op the limiter.
    pub fn validate_server_knobs(&self) -> Result<(), GwsError> {
        if self.rate_limit_rpm == Some(0) {
            return Err(GwsError::Validation(
                "server.rate_limit_rpm must be >= 1; omit the field to use the default of 600. \
                 (0 disables both the inbound per-client-IP and outbound per-service limiters; \
                 per-service outbound overrides belong in server.rate_limits, not here)"
                    .to_string(),
            ));
        }

        if let Some(limits) = &self.rate_limits {
            let mut keys: Vec<&String> = limits.keys().collect();
            keys.sort();
            for service in keys {
                if !KNOWN_SERVICES.contains(&service.as_str())
                    && !self.services.contains_key(service)
                {
                    return Err(GwsError::Validation(format!(
                        "server.rate_limits has unknown service key '{service}'. \
                         Known services: {}. \
                         Fix: use a service alias (or a name listed in \"services\"); \
                         server.rate_limits is a per-service outbound override map, \
                         not the HTTP request budget (that is server.rate_limit_rpm)",
                        KNOWN_SERVICES.join(", ")
                    )));
                }
                if limits[service] == 0 {
                    return Err(GwsError::Validation(format!(
                        "server.rate_limits.{service} must be >= 1; 0 would disable the \
                         outbound limiter for that service. Omit the entry to use the \
                         built-in default"
                    )));
                }
            }
        }

        // A malformed CIDR must not be tolerated: `http::parse_trusted_proxies`
        // skips entries it cannot parse, so a typo would silently fall back to
        // "trust nobody" (safe) or, worse, to a broader trust decision than the
        // operator intended if the typo happens to parse. Reject at load time
        // where the operator can see the error.
        for entry in &self.trusted_proxies {
            Self::validate_cidr(entry).map_err(|reason| {
                GwsError::Validation(format!(
                    "server.trusted_proxies entry '{entry}' is not a valid CIDR ({reason}). \
                     Use an address with an optional prefix, e.g. \"10.0.0.0/8\" or \
                     \"192.168.1.5/32\". Leave the list empty to ignore X-Forwarded-For \
                     entirely (correct for a directly exposed listener)"
                ))
            })?;
        }

        Ok(())
    }

    /// Human-readable warnings for policy shapes that silently weaken the
    /// documented guarantees.
    ///
    /// These are deliberately warnings, not errors: the configuration is
    /// usable, but it grants more than an operator reading "folder constraint"
    /// would expect. Returned lines are stable enough to print from
    /// `check-policy` and at startup.
    pub fn scoping_warnings(&self) -> Vec<String> {
        let mut warnings = Vec::new();

        for service in self.allowed_services() {
            let read_only = self.is_read_only(service);
            let Some(svc) = self.services.get(service) else {
                continue;
            };

            // `recursive: false` is the serde default, so an operator who
            // writes a `parents` constraint without `"recursive": true` gets a
            // list filter but no read-by-ID scoping (`execute.rs` gates the
            // ancestry walk on `recursive_parent_values`).
            let non_recursive_parents = svc.constraints.iter().any(|c| {
                c.param == "parents"
                    && c.mode == ConstraintMode::Restrict
                    && !c.recursive
                    && (c.location.as_deref() == Some("body")
                        || c.location.as_deref() == Some("body-write-only"))
            });
            if non_recursive_parents {
                warnings.push(format!(
                    "{service}: 'parents' constraint without \"recursive\": true — \
                     by-ID scoping (reads *and* writes) is inactive; the agent can \
                     read, modify, share or delete any file the credential can see by id"
                ));
            }

            if svc.constraints.is_empty() {
                if service == "calendar" {
                    warnings.push(
                        "calendar: no constraints — every calendar the credential can see \
                         (including \"primary\" and other users' shared calendars) is \
                         accessible; add a \"calendarId\" constraint"
                            .to_string(),
                    );
                } else if !read_only {
                    warnings.push(format!(
                        "{service}: service is not read-only and has no constraints — \
                         every resource the credential can see is accessible"
                    ));
                }
            }
        }

        if self.services.contains_key("gmail") && !self.is_read_only("gmail") {
            for (resource, method) in [
                ("settings.delegates", "create"),
                ("settings", "updateAutoForwarding"),
                ("settings.forwardingAddresses", "create"),
            ] {
                if !self.is_method_denied("gmail", resource, method) {
                    warnings.push(format!(
                        "gmail: '{resource}.{method}' is not denied — the agent can \
                         redirect or copy mail outside this mailbox; add it to \
                         \"denied_methods\""
                    ));
                }
            }
        }

        warnings
    }

    pub fn with_extra_parent(&self, service: &str, folder_id: &str) -> Self {
        let mut clone = self.clone();
        if let Some(svc) = clone.services.get_mut(service) {
            for c in &mut svc.constraints {
                if c.param == "parents"
                    && c.mode == ConstraintMode::Restrict
                    && !c.values.contains(&folder_id.to_string())
                {
                    c.values.push(folder_id.to_string());
                }
            }
        }
        clone
    }

    pub fn recursive_parent_values(&self, service: &str) -> Vec<&str> {
        self.constraints(service)
            .iter()
            .filter(|c| {
                c.param == "parents"
                    && c.recursive
                    && c.mode == ConstraintMode::Restrict
                    && (c.location.as_deref() == Some("body")
                        || c.location.as_deref() == Some("body-write-only"))
            })
            .flat_map(|c| c.values.iter().map(|v| v.as_str()))
            .collect()
    }

    pub fn writable_parent_folders(&self, service: &str) -> Vec<&str> {
        self.constraints(service)
            .iter()
            .filter(|c| {
                c.param == "parents"
                    && c.mode == ConstraintMode::Restrict
                    && c.access == Access::ReadWrite
                    && (c.location.as_deref() == Some("body")
                        || c.location.as_deref() == Some("body-write-only"))
            })
            .flat_map(|c| c.values.iter().map(|v| v.as_str()))
            .collect()
    }

    pub fn has_parent_constraints(&self, service: &str) -> bool {
        self.constraints(service).iter().any(|c| {
            c.param == "parents"
                && c.mode == ConstraintMode::Restrict
                && (c.location.as_deref() == Some("body")
                    || c.location.as_deref() == Some("body-write-only"))
        })
    }

    pub fn templates(&self) -> &[TemplateEntry] {
        &self.templates
    }

    pub fn find_template(&self, name_or_id: &str) -> Option<&TemplateEntry> {
        self.templates
            .iter()
            .find(|t| t.name == name_or_id || t.id == name_or_id)
    }

    pub fn is_origin_allowed(&self, origin: &str) -> bool {
        let Some(host) = origin_host(origin) else {
            return false;
        };

        if self.allowed_origins.is_empty() {
            return host == "localhost" || host == "127.0.0.1" || host == "::1";
        }

        // Normalize both sides through the same host extraction so that full
        // URLs, `host:port`, bracketed IPv6 and padded/mixed-case entries all
        // compare as plain lowercased hosts. Exact host equality (not a
        // substring test) keeps `internal.corp.com` from matching
        // `internal.corp.com.evil.com`.
        self.allowed_origins
            .iter()
            .filter_map(|entry| origin_host(entry))
            .any(|allowed| allowed == host)
    }

    pub fn allowed_services(&self) -> Vec<&str> {
        let mut names: Vec<&str> = self.services.keys().map(|s| s.as_str()).collect();
        names.sort();
        names
    }

    pub fn is_service_allowed(&self, name: &str) -> bool {
        self.services.contains_key(name)
    }

    pub fn is_read_only(&self, service: &str) -> bool {
        if self.global_read_only {
            return true;
        }
        self.services
            .get(service)
            .and_then(|s| s.read_only)
            .unwrap_or(false)
    }

    pub fn denied_methods(&self, service: &str) -> HashSet<&str> {
        self.services
            .get(service)
            .map(|s| s.denied_methods.iter().map(|m| m.as_str()).collect())
            .unwrap_or_default()
    }

    /// True when `resource.method` is denied by the service's
    /// `denied_methods` list, including the alias/leaf-name matching used by
    /// [`Self::check_method`].
    ///
    /// Helpers use this to close gaps where a different API method performs
    /// the same destructive action (for example `messages.modify` adding the
    /// `TRASH` system label stands in for `messages.trash`).
    pub fn is_method_denied(&self, service: &str, resource: &str, method: &str) -> bool {
        method_is_denied(&self.denied_methods(service), resource, method)
    }

    pub fn allowed_labels(&self, service: &str) -> &[String] {
        self.services
            .get(service)
            .map(|s| s.allowed_labels.as_slice())
            .unwrap_or(&[])
    }

    pub fn allowed_resources(&self, service: &str) -> &[String] {
        self.services
            .get(service)
            .map(|s| s.allowed_resources.as_slice())
            .unwrap_or(&[])
    }

    pub fn constraints(&self, service: &str) -> &[Constraint] {
        self.services
            .get(service)
            .map(|s| s.constraints.as_slice())
            .unwrap_or(&[])
    }

    pub fn check_method(
        &self,
        service: &str,
        resource: &str,
        method_name: &str,
        method: &RestMethod,
    ) -> Result<(), GwsError> {
        if !self.is_service_allowed(service) {
            return Err(GwsError::Validation(format!(
                "Service '{service}' is not allowed by policy. \
                 Fix: add {{\"name\": \"{service}\"}} to the \"services\" array in your policy file"
            )));
        }

        let is_write = method.http_method != "GET";

        if self.is_read_only(service) && is_write {
            return Err(GwsError::Validation(format!(
                "Service '{service}' is read-only; {method_name} ({}) is not allowed. \
                 Fix: set \"read_only\": false on the \"{service}\" service in your policy file",
                method.http_method
            )));
        }

        let denied = self.denied_methods(service);
        if method_is_denied(&denied, resource, method_name) {
            let full_name = format!("{resource}.{method_name}");
            return Err(GwsError::Validation(format!(
                "Method '{full_name}' is denied by policy. \
                 Fix: remove \"{method_name}\" from \"denied_methods\" in the \"{service}\" service"
            )));
        }

        Ok(())
    }

    /// True when a client-supplied delegation subject is allowed.
    ///
    /// An empty allowlist rejects every client-supplied subject: operators must
    /// opt in explicitly by listing the subjects they trust.
    pub fn is_subject_allowed(&self, subject: &str) -> bool {
        self.allowed_subjects
            .iter()
            .any(|allowed| allowed.eq_ignore_ascii_case(subject))
    }

    /// Resolve the delegation subject for a request.
    ///
    /// `requested` comes from client-controlled metadata (`_meta.user_email`),
    /// so it must match `server.allowed_subjects`. When the client does not ask
    /// for a subject, the operator-configured `delegate_subject` is used.
    pub fn resolve_delegation_subject(
        &self,
        requested: Option<&str>,
    ) -> Result<Option<String>, GwsError> {
        match requested {
            Some(subject) => {
                if self.is_subject_allowed(subject) {
                    Ok(Some(subject.to_string()))
                } else {
                    Err(GwsError::Validation(format!(
                        "Delegation subject '{subject}' is not in server.allowed_subjects. \
                         Fix: add \"{subject}\" to \"allowed_subjects\" in the \"server\" section \
                         of your policy file, or omit _meta.user_email"
                    )))
                }
            }
            None => Ok(self.delegate_subject.clone()),
        }
    }

    /// Enforce parameter/body constraints without knowing the resource.
    ///
    /// This is the legacy entry point: it delegates to
    /// [`Self::enforce_constraints_for`] with an empty resource, preserving the
    /// historical method-name-only behaviour for the `parents` requirement.
    /// Callers that know the resource (for example `execute.rs`) should use
    /// [`Self::enforce_constraints_for`] so that non-`files.create` writes are
    /// not mistaken for parented resource creation.
    pub fn enforce_constraints(
        &self,
        service: &str,
        method_name: &str,
        method: &RestMethod,
        params: &mut serde_json::Map<String, serde_json::Value>,
        body: &Option<serde_json::Value>,
    ) -> Result<(), GwsError> {
        self.enforce_constraints_for(service, "", method_name, method, params, body)
    }

    /// Enforce parameter/body constraints with the resource known.
    ///
    /// `resource` matters because the `parents` body field is only a creation
    /// target on `drive.files.create|copy`. Applying the "must specify parents"
    /// rule to every non-GET method of the `drive` service used to reject
    /// `permissions.create` (used by `gws_drive_share` and Docs image
    /// insertion), `files.update`-based helpers (rename, trash) and
    /// `files.delete` — none of which take a `parents` body. Those writes are
    /// scoped by the ancestry checks in `execute.rs`; this function must not
    /// re-impose a check they cannot satisfy.
    pub fn enforce_constraints_for(
        &self,
        service: &str,
        resource: &str,
        method_name: &str,
        method: &RestMethod,
        params: &mut serde_json::Map<String, serde_json::Value>,
        body: &Option<serde_json::Value>,
    ) -> Result<(), GwsError> {
        let constraints = self.constraints(service);
        if constraints.is_empty() {
            return Ok(());
        }

        let is_write = method.http_method != "GET";
        // copy/export are POST but only read the source param — params are read-inputs,
        // not write-targets. Body params (like parents) are still write-targets.
        let params_are_read_only = method_name == "copy" || method_name == "export";

        let mut by_param: HashMap<&str, Vec<&Constraint>> = HashMap::new();
        for c in constraints {
            by_param.entry(c.param.as_str()).or_default().push(c);
        }

        for (param, group) in &by_param {
            let restrict_group: Vec<&&Constraint> = group
                .iter()
                .filter(|c| c.mode == ConstraintMode::Restrict)
                .collect();
            let protect_group: Vec<&&Constraint> = group
                .iter()
                .filter(|c| c.mode == ConstraintMode::Protect)
                .collect();

            let all_values: Vec<&str> = restrict_group
                .iter()
                .flat_map(|c| c.values.iter().map(|v| v.as_str()))
                .collect();
            let rw_values: Vec<&str> = restrict_group
                .iter()
                .filter(|c| c.access == Access::ReadWrite)
                .flat_map(|c| c.values.iter().map(|v| v.as_str()))
                .collect();
            let protect_ro_values: Vec<&str> = protect_group
                .iter()
                .filter(|c| c.access == Access::ReadOnly)
                .flat_map(|c| c.values.iter().map(|v| v.as_str()))
                .collect();

            let location = group[0].location.as_deref();
            let is_body = location == Some("body") || location == Some("body-write-only");
            let write_only = location == Some("body-write-only");
            // `body-write-only` skips the read-side query filter on get/export
            // style reads, which execute.rs enforces by id. `list` responses
            // enumerate every object, so they must always be narrowed to the
            // allowed parent folders — otherwise `files.list` leaks every file
            // id and each id feeds the read-scope bypasses.
            let skip_read_filter = write_only && !is_write && method_name != "list";

            if is_body {
                if !restrict_group.is_empty() && !skip_read_filter {
                    self.enforce_body_constraint(
                        service,
                        resource,
                        param,
                        &all_values,
                        &rw_values,
                        is_write,
                        write_only,
                        method_name,
                        params,
                        body,
                    )?;
                }
                if is_write {
                    if !restrict_group.is_empty() {
                        self.enforce_parent_params(param, &all_values, &rw_values, params)?;
                    }
                    if !protect_ro_values.is_empty() {
                        self.enforce_body_protect(param, &protect_ro_values, body)?;
                        self.enforce_parent_params_protect(param, &protect_ro_values, params)?;
                    }
                }
            } else {
                let param_is_write = is_write && !params_are_read_only;
                if !restrict_group.is_empty() {
                    self.enforce_param_constraint(
                        param,
                        &all_values,
                        &rw_values,
                        param_is_write,
                        params,
                    )?;
                }
                if param_is_write && !protect_ro_values.is_empty() {
                    self.enforce_param_protect(param, &protect_ro_values, params)?;
                }
            }
        }

        Ok(())
    }

    fn enforce_body_constraint(
        &self,
        service: &str,
        resource: &str,
        param: &str,
        all_values: &[&str],
        rw_values: &[&str],
        is_write: bool,
        write_only: bool,
        method_name: &str,
        params: &mut serde_json::Map<String, serde_json::Value>,
        body: &Option<serde_json::Value>,
    ) -> Result<(), GwsError> {
        if !is_write {
            let filter_parts: Vec<String> = all_values
                .iter()
                .map(|id| format!("'{id}' in {param}"))
                .collect();
            let constraint = filter_parts.join(" or ");

            if let Some(serde_json::Value::String(existing)) = params.get("q") {
                // The caller's `q` is spliced into a parenthesised wrapper
                // below. Parenthesising only groups a *single* expression, so
                // `trashed = false) or (starred = true` would close the wrapper
                // and re-associate the policy constraint with `or`. Validating
                // balance first makes the wrapper sound: a parenthesised
                // expression with balanced parens and terminated single-quoted
                // literals cannot end before the closing parenthesis we append,
                // so the `and` stays at the top level. Top-level `or` inside
                // the wrapper is legitimate and stays grouped.
                validate_drive_query(existing)?;
                let combined = format!("({existing}) and ({constraint})");
                params.insert("q".to_string(), serde_json::Value::String(combined));
            } else {
                params.insert("q".to_string(), serde_json::Value::String(constraint));
            }
            return Ok(());
        }

        let body_values: Vec<&str> = body
            .as_ref()
            .and_then(|b| b.get(param))
            .map(|v| match v {
                serde_json::Value::Array(arr) => arr.iter().filter_map(|v| v.as_str()).collect(),
                serde_json::Value::String(s) => vec![s.as_str()],
                _ => vec![],
            })
            .unwrap_or_default();

        if body_values.is_empty() {
            // `body-write-only` relaxes the requirement for writes where the
            // field is genuinely optional (renames, metadata updates), but a
            // create-class write that omits `parents` lands in My Drive root,
            // outside the configured folder tree, so it must be rejected.
            if write_only && !is_create_class_write(service, resource, method_name) {
                return Ok(());
            }
            // With the resource known, only `drive.files.create|copy` create a
            // parented resource. Every other write (`permissions.*`,
            // `files.update`, `files.delete`, docs/sheets/slides writes) has no
            // `parents` field to satisfy: requiring one is a functional bug,
            // and the by-ID ancestry checks in `execute.rs` scope those
            // writes instead. A `files.update` that moves a file via
            // `addParents`/`removeParents` still has to name its destination
            // parent under a strict `location: "body"` constraint.
            if !write_only
                && !resource.is_empty()
                && !is_create_class_write(service, resource, method_name)
                && !carries_parent_move(param, params)
            {
                return Ok(());
            }
            return Err(GwsError::Validation(format!(
                "Write denied: '{param}' must be specified when constraints are configured. \
                 Allowed read-write values: {rw}. \
                 Fix: include \"{param}\" in the request body",
                rw = rw_values.join(", ")
            )));
        }

        for val in &body_values {
            if !all_values.contains(val) {
                return Err(GwsError::Validation(format!(
                    "Write denied: {param} value '{val}' is not in the allowed list. \
                     Fix: add it to a constraint on \"{param}\" in your policy file"
                )));
            }
            if !rw_values.contains(val) {
                return Err(GwsError::Validation(format!(
                    "Write denied: {param} value '{val}' is read-only. \
                     Fix: change its access to \"read-write\" in your policy file"
                )));
            }
        }

        Ok(())
    }

    fn enforce_parent_params(
        &self,
        param: &str,
        all_values: &[&str],
        rw_values: &[&str],
        params: &serde_json::Map<String, serde_json::Value>,
    ) -> Result<(), GwsError> {
        let add_key = format!("add{}", capitalize(param));
        let remove_key = format!("remove{}", capitalize(param));

        for key in [&add_key, &remove_key] {
            if let Some(serde_json::Value::String(ids)) = params.get(key.as_str()) {
                for id in ids.split(',').map(|s| s.trim()) {
                    if id.is_empty() {
                        continue;
                    }
                    if !all_values.contains(&id) {
                        return Err(GwsError::Validation(format!(
                            "Write denied via {key}: '{id}' is not in the allowed list. \
                             Fix: add it to a constraint on \"{param}\" in your policy file"
                        )));
                    }
                    if !rw_values.contains(&id) {
                        return Err(GwsError::Validation(format!(
                            "Write denied via {key}: '{id}' is read-only. \
                             Fix: change its access to \"read-write\" in your policy file"
                        )));
                    }
                }
            }
        }

        Ok(())
    }

    /// Protect-mode counterpart to [`Self::enforce_parent_params`].
    ///
    /// A file inside a protected (read-only) folder must not be moved out of it
    /// (`removeParents`), and no file may be moved into it (`addParents`).
    fn enforce_parent_params_protect(
        &self,
        param: &str,
        protect_ro_values: &[&str],
        params: &serde_json::Map<String, serde_json::Value>,
    ) -> Result<(), GwsError> {
        let add_key = format!("add{}", capitalize(param));
        let remove_key = format!("remove{}", capitalize(param));

        for (key, action) in [(&remove_key, "moved out of"), (&add_key, "moved into")] {
            if let Some(serde_json::Value::String(ids)) = params.get(key.as_str()) {
                for id in ids.split(',').map(|s| s.trim()) {
                    if id.is_empty() {
                        continue;
                    }
                    if protect_ro_values.contains(&id) {
                        return Err(GwsError::Validation(format!(
                            "Write denied via {key}: '{id}' is protected as read-only; \
                             the file cannot be {action} it. \
                             Fix: change its access to \"read-write\" or remove the protect constraint"
                        )));
                    }
                }
            }
        }

        Ok(())
    }

    fn enforce_param_constraint(
        &self,
        param: &str,
        all_values: &[&str],
        rw_values: &[&str],
        is_write: bool,
        params: &serde_json::Map<String, serde_json::Value>,
    ) -> Result<(), GwsError> {
        let Some(serde_json::Value::String(value)) = params.get(param) else {
            return Err(GwsError::Validation(format!(
                "Constraints are configured for '{param}' but it was not specified. \
                 Allowed: {all}. \
                 Fix: include \"{param}\" in the request params",
                all = all_values.join(", ")
            )));
        };

        if !all_values.contains(&value.as_str()) {
            return Err(GwsError::Validation(format!(
                "Value '{value}' for '{param}' is not allowed by policy. Allowed: {all}. \
                 Fix: add {{\"param\": \"{param}\", \"values\": [\"{value}\"]}} \
                 to the \"constraints\" array in your policy file",
                all = all_values.join(", ")
            )));
        }

        if is_write && !rw_values.contains(&value.as_str()) {
            return Err(GwsError::Validation(format!(
                "'{param}' value '{value}' is read-only; write operations are not allowed. \
                 Fix: change its access to \"read-write\" in your policy file"
            )));
        }

        Ok(())
    }

    fn enforce_param_protect(
        &self,
        param: &str,
        protect_ro_values: &[&str],
        params: &serde_json::Map<String, serde_json::Value>,
    ) -> Result<(), GwsError> {
        if let Some(serde_json::Value::String(value)) = params.get(param)
            && protect_ro_values.contains(&value.as_str())
        {
            return Err(GwsError::Validation(format!(
                "'{param}' value '{value}' is protected as read-only; write operations \
                     are not allowed. \
                     Fix: change its access to \"read-write\" or remove the protect constraint"
            )));
        }
        Ok(())
    }

    fn enforce_body_protect(
        &self,
        param: &str,
        protect_ro_values: &[&str],
        body: &Option<serde_json::Value>,
    ) -> Result<(), GwsError> {
        let body_values: Vec<&str> = body
            .as_ref()
            .and_then(|b| b.get(param))
            .map(|v| match v {
                serde_json::Value::Array(arr) => arr.iter().filter_map(|v| v.as_str()).collect(),
                serde_json::Value::String(s) => vec![s.as_str()],
                _ => vec![],
            })
            .unwrap_or_default();

        for val in &body_values {
            if protect_ro_values.contains(val) {
                return Err(GwsError::Validation(format!(
                    "Write denied: {param} value '{val}' is protected as read-only. \
                     Fix: change its access to \"read-write\" or remove the protect constraint"
                )));
            }
        }
        Ok(())
    }
}

fn capitalize(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
    }
}

/// Validate a caller-supplied Drive `q` filter before the policy wraps it.
///
/// The wrapper is `({q}) and ({policy filter})`, so `q` is trusted to be one
/// complete expression. Balance is the sufficient condition: once every
/// single-quoted literal is terminated and the parenthesis depth never goes
/// negative and returns to zero, nothing inside `q` can close the wrapper we
/// append, and no unterminated literal can swallow it. A top-level `or` inside
/// `q` stays inside the grouping, which is why legitimate disjunctive filters
/// must not be rejected.
fn validate_drive_query(q: &str) -> Result<(), GwsError> {
    let mut depth: i64 = 0;
    let mut in_literal = false;
    let mut escaped = false;

    for ch in q.chars() {
        if ch.is_control() {
            return Err(GwsError::Validation(format!(
                "Rejected 'q': contains control character U+{:04X}. The caller-supplied \
                 filter is wrapped in the policy's folder constraint; supply a single \
                 clean expression",
                ch as u32
            )));
        }

        if in_literal {
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == '\'' {
                in_literal = false;
            }
            continue;
        }

        match ch {
            '\'' => in_literal = true,
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth < 0 {
                    return Err(GwsError::Validation(
                        "Rejected 'q': unbalanced parentheses. The caller-supplied filter \
                         is wrapped in the policy's folder constraint, so it must be a \
                         single balanced expression"
                            .to_string(),
                    ));
                }
            }
            _ => {}
        }
    }

    if in_literal {
        return Err(GwsError::Validation(
            "Rejected 'q': unterminated single-quoted string literal. The caller-supplied \
             filter is wrapped in the policy's folder constraint, so it must be a single \
             balanced expression"
                .to_string(),
        ));
    }
    if depth != 0 {
        return Err(GwsError::Validation(
            "Rejected 'q': unbalanced parentheses. The caller-supplied filter is wrapped \
             in the policy's folder constraint, so it must be a single balanced expression"
                .to_string(),
        ));
    }

    Ok(())
}

/// True when `params` carries an `add<Param>`/`remove<Param>` move for `param`.
fn carries_parent_move(param: &str, params: &serde_json::Map<String, serde_json::Value>) -> bool {
    params.contains_key(&format!("add{}", capitalize(param)))
        || params.contains_key(&format!("remove{}", capitalize(param)))
}

/// Methods whose body creates a new resource. Omitting a constrained parent on
/// these writes places the resource outside the allowed folder tree.
///
/// Only `drive.files.create|copy` take a `parents` body field. When the caller
/// cannot name the resource (`resource` is empty) the historical
/// method-name-only rule is kept, so existing call sites behave identically
/// until they switch to [`Policy::enforce_constraints_for`].
fn is_create_class_write(service: &str, resource: &str, method_name: &str) -> bool {
    if !matches!(method_name, "create" | "copy") {
        return false;
    }
    if resource.is_empty() {
        return true;
    }
    service == "drive" && resource == "files"
}

/// Every method name that policy should treat as equivalent to
/// `{resource}.{method}`.
///
/// Denying one member of a family blocks all of them, so `messages.send`
/// cannot be bypassed with `drafts.send`, nor `files.delete` with
/// `files.emptyTrash`. Only destructive/mutating methods are aliased.
pub fn method_aliases(resource: &str, method: &str) -> Vec<String> {
    let mut names = vec![format!("{resource}.{method}")];
    let mut push = |name: &str| {
        if !names.iter().any(|n| n == name) {
            names.push(name.to_string());
        }
    };

    match (resource, method) {
        // Sending a draft is sending a message.
        ("users.drafts" | "drafts", "send") => {
            push("messages.send");
            push("users.messages.send");
        }
        ("users.messages" | "messages", "send") => {
            push("drafts.send");
            push("users.drafts.send");
        }
        // emptyTrash permanently destroys files, same as delete.
        ("files", "emptyTrash") => push("files.delete"),
        ("files", "delete") => push("files.emptyTrash"),
        // batchDelete permanently destroys messages, same as delete.
        ("users.messages" | "messages", "batchDelete") => {
            push("messages.delete");
            push("users.messages.delete");
        }
        ("users.messages" | "messages", "delete") => {
            push("messages.batchDelete");
            push("users.messages.batchDelete");
        }
        _ => {}
    }

    names
}

/// Host part of an `allowed_origins` entry or a presented `Origin` header.
///
/// Accepts bare hosts (`internal.corp.com`), `host:port`
/// (`internal.corp.com:8443`), bracketed IPv6 (`[::1]:8443`) and full origins
/// (`https://app.example.com`). The host is lowercased and unbracketed so both
/// sides of [`Policy::is_origin_allowed`] compare case-insensitively.
///
/// `http::host_from_origin_entry` implements the same normalization but is
/// private to that module, so the logic is duplicated here rather than
/// loosening `http`'s visibility.
fn origin_host(entry: &str) -> Option<String> {
    let entry = entry.trim();
    if entry.is_empty() {
        return None;
    }

    let host = if entry.contains("://") {
        // Full origin: the URL parser handles userinfo, ports and bracketed
        // IPv6. `https://internal.corp.com@evil.com` yields `evil.com`, so a
        // userinfo-spoofed origin cannot match an allowlisted bare host.
        url::Url::parse(entry).ok()?.host_str()?.to_string()
    } else if let Some(rest) = entry.strip_prefix('[') {
        // Bracketed IPv6, with or without a port.
        rest.split_once(']')
            .map(|(host, _)| host)
            .unwrap_or(rest)
            .to_string()
    } else if entry.matches(':').count() == 1 {
        // `host:port`.
        entry
            .split_once(':')
            .map(|(host, _)| host)
            .unwrap_or(entry)
            .to_string()
    } else {
        // Bare hostname, or bare IPv6 (`::1`) with no port.
        entry.to_string()
    };

    let host = host
        .trim_start_matches('[')
        .trim_end_matches(']')
        .trim()
        .to_ascii_lowercase();
    (!host.is_empty()).then_some(host)
}

fn method_is_denied(denied: &HashSet<&str>, resource: &str, method: &str) -> bool {
    method_aliases(resource, method).iter().any(|name| {
        if denied.contains(name.as_str()) {
            return true;
        }
        // Leaf-name matching keeps `deny: ["send"]` and `deny: ["messages.send"]`
        // both effective.
        if let Some(leaf) = name.rsplit('.').next()
            && denied.contains(leaf)
        {
            return true;
        }
        denied.iter().any(|d| name.ends_with(&format!(".{d}")))
    })
}

